"""Render reports/data_report.md from the stats.json / leakage_report.json files."""
from __future__ import annotations

import json

from .config import (DATASETS, HISTORY_SPLITS, PROCESSED_DIR, RANDOM_SEED, REPORTS_DIR,
                     SESSION_GAP_HOURS, SPLIT_RATIOS)
from .plots import LABELS


def _pct(x):
    return f"{x:.1%}"


def _table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def render() -> str:
    S, L = {}, {}
    for n in DATASETS:
        p = PROCESSED_DIR / n / "stats.json"
        if p.exists():
            S[n] = json.loads(p.read_text(encoding="utf-8"))
            L[n] = json.loads((PROCESSED_DIR / n / "leakage_report.json").read_text(encoding="utf-8"))
    names = list(S)
    md = ["# TraceX data report (Member 1: data engineering & preprocessing)", "",
          "Generated by `python -m tracex_data report` from the pipeline outputs; do not edit by hand.", "",
          "## Protocol", "",
          f"- Session rule: a new trajectory starts at a gap of **>= {SESSION_GAP_HOURS} h** "
          "(and never spans two users or two splits).",
          f"- Split: chronological on the global timeline, {'/'.join(str(int(r*100)) for r in SPLIT_RATIOS)} "
          "train/val/test by check-in time.",
          "- Val/test keep only users and POIs seen in training; trajectories need >= 2 check-ins.",
          "- Task: predict the **last check-in** of each val/test trajectory from its prefix and the user's history.",
          f"- History (fixed definition, used for E2): the user's trajectories in **{'+'.join(HISTORY_SPLITS)}** "
          "that end before the target trajectory starts. "
          "`is_revisit` = target POI appears in history **or** in the current prefix.",
          f"- Evaluation sample: 500 test instances per dataset, seed {RANDOM_SEED}; debug subset of 20.", ""]

    md += ["## Dataset summary", "", _table(
        ["", *[LABELS[n] for n in names]],
        [["Raw rows", *[f"{S[n]['raw_rows']:,}" for n in names]],
         ["Users", *[f"{S[n]['overall']['users']:,}" for n in names]],
         ["POIs", *[f"{S[n]['overall']['pois']:,}" for n in names]],
         ["Categories", *[S[n]['overall']['categories'] for n in names]],
         ["Check-ins", *[f"{S[n]['overall']['checkins']:,}" for n in names]],
         ["Trajectories", *[f"{S[n]['overall']['trajectories']:,}" for n in names]],
         ["Period", *[f"{S[n]['overall']['time_span'][0][:10]} to {S[n]['overall']['time_span'][1][:10]}" for n in names]],
         ["Check-ins / user (median)", *[S[n]['overall']['checkins_per_user']['median'] for n in names]],
         ["Trajectories / user (median)", *[S[n]['overall']['trajectories_per_user']['median'] for n in names]],
         ["Trajectory length (mean / median)", *[f"{S[n]['overall']['trajectory_length']['mean']} / "
                                                 f"{S[n]['overall']['trajectory_length']['median']}" for n in names]],
         ["Filters (min POI / user check-ins)", *[f"{S[n]['filters']['min_poi_checkins']} / "
                                                  f"{S[n]['filters']['min_user_checkins']}" for n in names]],
         ["Published reference (users / POIs)", *[f"{S[n]['published_reference']['users']:,} / "
                                                  f"{S[n]['published_reference']['pois']:,}"
                                                  if 'published_reference' in S[n] else "n/a" for n in names]]]), ""]

    md += ["## Splits", "", _table(
        ["Dataset", "Split", "Check-ins", "Trajectories", "Users", "POIs", "Split boundary"],
        [[LABELS[n], s, f"{v['checkins']:,}", f"{v['trajectories']:,}", v["users"], v["pois"],
          {"train": f"< {S[n]['split_cutoffs']['train_before']}",
           "val": f"< {S[n]['split_cutoffs']['val_before']}", "test": "rest"}[s]]
         for n in names for s, v in S[n]["per_split"].items()]), ""]

    md += ["## Cleaning and filtering log", ""]
    for n in names:
        md += [f"**{LABELS[n]}**", "", _table(["Step", "Rows before", "Rows after", "Removed"],
               [[l["step"], f"{l['rows_before']:,}", f"{l['rows_after']:,}", f"{l['removed']:,}"]
                for l in S[n]["pipeline_log"]]), ""]

    md += ["## Test instances and revisit-versus-new (E2)", "", _table(
        ["Dataset", "Set", "Instances", "Revisit", "In history", "In prefix", "New to user",
         "Prefix len (median)", "History check-ins (median)"],
        [[LABELS[n], k, v["n"], _pct(v["revisit_rate"]), _pct(v["target_in_history_rate"]),
          _pct(v["target_in_prefix_rate"]), _pct(v["new_poi_rate"]), v["prefix_len"]["median"],
          v["history_checkins"]["median"]]
         for n in names for k, v in S[n]["instances"].items()]), ""]

    md += ["## POI coverage", "", _table(
        ["Dataset", "POIs in train", "Train check-ins / POI (median)", "Share of check-ins on top 1% POIs",
         "POIs with <= 5 train check-ins", "Test POIs seen in train", "Distinct test target POIs"],
        [[LABELS[n], f"{c['pois_in_train']:,}", c["train_checkins_per_poi"]["median"],
          _pct(c["share_of_train_checkins_on_top_1pct_pois"]), _pct(c["share_of_pois_with_<=5_train_checkins"]),
          _pct(c["test_pois_seen_in_train"]), c["test_target_pois_distinct"]]
         for n in names for c in [S[n]["poi_coverage"]]]), ""]

    named = [n for n in names if "name_coverage" in S[n]]
    if named:
        md += ["## Venue-name coverage (E3)", ""]
        for n in named:
            c = S[n]["name_coverage"]
            md += [f"**{LABELS[n]}**: POIs with name {_pct(c['pois_with_name'])}, with address "
                   f"{_pct(c['pois_with_address'])}, test targets with name {_pct(c['test_targets_with_name'])}, "
                   f"{c['distinct_names']:,} distinct names; {_pct(c['pois_sharing_a_name_with_another_poi'])} of POIs "
                   "share a name with another POI (chains), so aliases must be assigned per POI ID, not per name.", ""]

    md += ["## Leakage checks", ""]
    for n in names:
        checks = L[n]["checks"]
        md += [f"**{LABELS[n]}**: {sum(c['passed'] for c in checks)}/{len(checks)} passed", "",
               _table(["Check", "Result", "Detail"],
                      [[c["name"], "PASS" if c["passed"] else "**FAIL**", c["detail"]] for c in checks]), ""]

    md += ["## Sample fingerprints", "",
           "Every member should get the same fingerprints after running the pipeline; if not, the data differ.", "",
           _table(["Dataset", "Sample", "SHA-256 prefix of instance IDs"],
                  [[LABELS[n], k, f"`{v}`"] for n in names for k, v in S[n]["sample_fingerprints"].items()]), ""]

    md += ["## Figures", "",
           "![POI popularity](figures/poi_popularity_longtail.png)", "",
           "![Trajectory length](figures/trajectory_length.png)", "",
           "![Hour of day](figures/hour_of_day.png)", "",
           "![Revisit vs new](figures/revisit_vs_new.png)", ""]
    return "\n".join(md)


def write_report() -> str:
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    path = REPORTS_DIR / "data_report.md"
    path.write_text(render(), encoding="utf-8")
    return str(path)
